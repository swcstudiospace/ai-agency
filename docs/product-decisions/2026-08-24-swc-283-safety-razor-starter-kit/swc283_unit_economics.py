#!/usr/bin/env python3
"""SWC-283 — Safety razor starter kit (bamboo handle + stand + blades tin).

Per-unit P&L rebuild, returns-rate sensitivity, hurdle COGS ceilings,
and revisit-trigger verification. All assumptions explicit and sourced inline.
Outputs a markdown summary to stdout (saved alongside as swc283_economics_output.md).

Source data: ai-agency/tmp/runs/product_rank_20260816T200140Z.json
(candidate "Safety razor starter kit with bamboo handle + stand + blades tin",
 composite_score 54.3, healthy=false, decision=NO-GO).
"""
# ----------------------------------------------------------------------------
# Stated inputs (rank-fallback run 2026-08-16)
# ----------------------------------------------------------------------------
PRICE = 36.99          # suggested retail price
COGS = 7.50            # razor + stand + blades tin + how-to card
SHIP = 5.50            # outbound shipping per order
STATED_CM = 2.77       # contribution margin claimed by original rank ($)
STATED_PCT = 7.5       # ... (%)

# ----------------------------------------------------------------------------
# Rebuild assumptions (house conventions; each explicit)
# ----------------------------------------------------------------------------
FEE_PCT = 0.079        # payment/platform fees: 7.9% of price (house formula)
FEE_FIX = 0.30         # ...plus $0.30 fixed per order  (house formula, SWC-135 §1)
CPA_GATE = 18.00       # portfolio planning CPA used by the Aug-16 rank run
HURDLE = 0.20          # portfolio contribution-margin hurdle: >= 20%

# Return write-off components (returned kit unsellable: opened blades = zero resale)
R_LOST_COGS = COGS     # kit written off
R_LOST_SHIP = SHIP     # outbound freight sunk
R_NONREFUND_FEES = PRICE * FEE_PCT * 0.20 + FEE_FIX   # ~$0.88 non-refundable portion
R_PROCESS_LABOR = 4.00                                # RMA handling labor
R_REVERSE_FREIGHT = 6.00                              # return label / inbound freight


def fees(price):
    return price * FEE_PCT + FEE_FIX


def loss_per_return():
    return R_LOST_COGS + R_LOST_SHIP + R_NONREFUND_FEES + R_PROCESS_LABOR + R_REVERSE_FREIGHT


def cm_at(return_rate=0.0, cpa=CPA_GATE, price=PRICE, cogs=COGS):
    """Expected post-ad CM per ordered unit."""
    return price - cogs - SHIP - fees(price) - cpa - return_rate * loss_per_return()


def max_cac(return_rate):
    return PRICE - COGS - SHIP - fees(PRICE) - return_rate * loss_per_return()


def main():
    out = []
    add = out.append
    L = loss_per_return()
    base = cm_at()
    add("# SWC-283 Economics Output — generated by `swc283_unit_economics.py`\n")
    add("## Base-case per-unit P&L\n")
    add("| Line | Per unit |")
    add("|---|---|")
    add(f"| Retail price | ${PRICE:.2f} |")
    add(f"| COGS | −${COGS:.2f} |")
    add(f"| Outbound shipping | −${SHIP:.2f} |")
    add(f"| Fees ({FEE_PCT:.1%} × ${PRICE:.2f} + ${FEE_FIX:.2f}) | −${fees(PRICE):.2f} |")
    add(f"| **Pre-ad contribution** | **${base + CPA_GATE:.2f} ({(base+CPA_GATE)/PRICE:.1%})** |")
    add(f"| Planning CPA | −${CPA_GATE:.2f} |")
    add(f"| **Post-ad CM** | **${base:.2f} ({base/PRICE:.2%})** — hurdle ≥{HURDLE:.0%} |")
    xcheck = "MATCH" if abs(base - STATED_CM) < 0.01 else "MISMATCH"
    add(f"\nCross-check vs stated CM ${STATED_CM:.2f} ({STATED_PCT}%): **{xcheck}** "
        f"(stated `variable_cost` $34.22 = price − CM, consistent with this build-up).\n")

    add("## Returns-rate sensitivity\n")
    add(f"Out-of-pocket loss per return ≈ ${L:.2f} = kit write-off ${R_LOST_COGS:.2f} "
        f"+ lost ship ${R_LOST_SHIP:.2f} + non-refundable fees ${R_NONREFUND_FEES:.2f} "
        f"+ labor ${R_PROCESS_LABOR:.2f} + reverse freight ${R_REVERSE_FREIGHT:.2f}\n")
    add("| Return rate | Expected post-ad CM | Margin % | Max tolerable CAC |")
    add("|---|---|---|---|")
    for r in (0.0, 0.05, 0.10, 0.15):
        e = cm_at(r)
        flag = " **(negative)**" if e < 0 else ""
        add(f"| {r:.0%} | ${e:+.2f}{flag} | {e/PRICE:+.1%} | ${max_cac(r):.2f} |")
    add(f"\nNegative-CM threshold: return rate > {base/L:.1%}.")
    add("\n## Hurdle COGS ceilings (≥20% CM at $36.99)\n")
    c0 = PRICE - SHIP - fees(PRICE) - CPA_GATE - HURDLE * PRICE
    c10 = PRICE - SHIP - fees(PRICE) - CPA_GATE - 0.10 * L - HURDLE * PRICE
    add(f"- Zero returns: COGS ≤ **${max(c0,0):.2f}**")
    add(f"- 10% returns allowance: COGS ≤ **${max(c10,0):.2f}**")
    add("(Estimated actual COGS $7.50 — both ceilings unreachable.)\n")

    add("## Revisit-trigger verification (any ONE reopens evaluation)\n")
    aov, bcogs = 59.00, 13.00
    t1 = cm_at(0.10, price=aov, cogs=bcogs)
    add(f"- **T1** bundle/AOV ≥ $59 @ blended COGS $13: CM ${t1:+.2f} ({t1/aov:.1%}) → "
        f"{'CLEARS' if t1/aov >= HURDLE else 'fails'} ≥20% hurdle")
    t4 = cm_at(0.10, cpa=10.00)
    add(f"- **T4** proven CAC ≤ $10 @ 10% returns: CM ${t4:+.2f} ({t4/PRICE:.1%}) → "
        f"{'CLEARS' if t4/PRICE >= HURDLE else 'fails'} ≥20% hurdle")
    add("- **T2** pilot returns ≤5% @ ≥4.2★: removes R1 blocker; CM at 5% returns "
        f"${cm_at(0.05):+.2f} — still needs T1/T4 for the hurdle")
    add("- **T3** compliant blade lanes ≤$0.75/order: caps R3 at "
        f"{0.75/base:.0%} of the $2.77 margin")
    print("\n".join(out))


if __name__ == "__main__":
    main()
